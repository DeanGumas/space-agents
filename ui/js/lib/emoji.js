export const EMOJI_CATEGORIES = Object.entries(RAW).map(([name, items]) => ({
  name,
  items: items.map(([char, keywords]) => ({ char, keywords })),
}));

export function searchEmoji(query) {
  const q = query.trim().toLowerCase();
  if (!q) return null;
  return EMOJI_CATEGORIES.flatMap((c) => c.items).filter((e) => e.keywords.includes(q) || e.char === q);
}

